#!/usr/bin/env python3
"""Turn the output of evidence/depgraph/depquery.py into the number macros and tables of the paper.
Usage: python3 -I make_tables.py <dir with depquery.json and the .tsv files> <paper dir>
Every number in the paper that comes from the dependency graph is produced here, not typed by hand."""
import sys, os, json
qdir, pdir = sys.argv[1], sys.argv[2]
R = json.load(open(os.path.join(qdir, "depquery.json"), encoding="utf-8"))
os.makedirs(os.path.join(pdir, "tables"), exist_ok=True)
c = lambda n: f"{n:,}"
T = R["targets"]
def tgt(k): return T[k]
div = tgt("Formalism.L2.DIV.divClausesR_of")["cone"]
green = tgt("UpperTheory.Top.every_character_of_green_v_win")["cone"]
pack = tgt("UpperTheory.Lit.nonempty_hyps_definite_side_of_closed_bound")["cone"]
lib = sum(R["by_kind_library"].values()); proj = sum(R["by_kind_project"].values())
M = {
 "Ndecl": c(R["nodes"]), "Nlines": "1,080,769,508", "Nexprs": "1,065,214,335",
 "NedgesT": c(R["type_edges"]), "NedgesV": c(R["value_edges"]), "Nedges": c(R["type_edges"] + R["value_edges"]),
 "NmathlibNames": "771,129", "Nlib": c(lib), "Nproj": c(proj), "NprojThm": c(R["by_kind_project"]["thm"]),
 "NstmtMain": c(R["main_statement_cone"]["all"]), "NstmtMainProj": c(R["main_statement_cone"]["project"]),
 "NconeMain": c(R["main_cone"]["all"]), "NconeProj": c(R["main_cone"]["project"]), "NconeProjThm": c(R["main_cone"]["project_theorems"]),
 "NanyGeo": c(R["dependents"]["GlobalTheory.Mem.Top.Bl.anyGeometry"]["count"]),
 "NgeoDeg": c(R["dependents"]["Formalism.L2.Geo.geoDegenerate"]["count"]),
 "Nflagged": c(R["dependents_union_flagged"]["all"]), "NflaggedThm": c(R["dependents_union_flagged"]["project_theorems"]),
 "NfreeProj": c(R["cone_free_of_flagged"]["project"]), "NfreeProjThm": c(R["cone_free_of_flagged"]["project_theorems"]),
 "NifaceDeps": c(R["type_dependents"]["Formalism.BasicNotions.DV.Geo"]["all"]),
 "NaccDirect": c(R["geo_accessors"]["direct_referrers"]), "NaccThmProof": c(R["geo_accessors"]["theorems_whose_proof_refers"]),
 "Nacc": c(R["geo_accessors"]["accessors_in_export"]),
 "NdivInputs": "38",
 "NdivClausesAll": c(div["all"]), "NdivClausesProj": c(div["project"]), "NdivClausesThm": c(div["project_theorems"]),
 "NgreenAll": c(green["all"]), "NgreenProj": c(green["project"]), "NgreenThm": c(green["project_theorems"]),
 "NpackageAll": c(pack["all"]), "NpackageProj": c(pack["project"]), "NpackageThm": c(pack["project_theorems"]),
 "NplaceLP": c(R["dependents"]["Formalism.L2.LPTiedPlaceholder"]["count"]),
 "NplaceNT": c(R["dependents"]["GlobalTheory.HeightCounting.NTiedGPlaceholder"]["count"]),
 "NgeoTiedP": c(R["type_dependents"]["Formalism.L2.Geo.GeoTiedP"]["all"]) if "Formalism.L2.Geo.GeoTiedP" in R["type_dependents"] else "n/a",
 "NgeoOver": c(R["type_dependents"]["Formalism.L2.Geo.GeoOver"]["all"]) if "Formalism.L2.Geo.GeoOver" in R["type_dependents"] else "n/a",
 "NdivXdeps": c(R["type_dependents"]["Formalism.BasicNotions.DivX"]["all"]),
}
with open(os.path.join(pdir, "results_v2.tex"), "w", encoding="utf-8") as f:
    f.write("% Generated by make_tables.py from evidence/depgraph/query/depquery.json. Do not edit by hand.\n")
    for k, v in M.items(): f.write("\\newcommand{\\%s}{%s}\n" % (k, v))
    f.write(open(os.path.join(pdir, "results_text.tex"), encoding="utf-8").read())

FLAG = ["anyGeometry", "geoDegenerate", "algDegenerate", "padDegenerate", "mdlJunk", "cxJunk", "divXFl", "geoOver_stages", "geoExample", "pointGeo", "x0", "provisionalDivX", "graft"]
ROUTE = [("riemannHypothesis", "riemannHypothesis"), ("UpperTheory.FinalTheorems.everyCharacter", "everyCharacter"),
         ("UpperTheory.Lit.every_character_of_theta_integrals_local_matching", "every_character_of_theta_integrals_local_matching"),
         ("UpperTheory.Lit.nonempty_hyps_definite_side_of_closed_bound", "nonempty_hyps_definite_side_of_closed_bound"),
         ("UpperTheory.Top.every_character_of_green_v_win", "every_character_of_green_v_win"),
         ("UpperTheory.Top.zero_free_all_of_green_v_win", "zero_free_all_of_green_v_win"),
         ("UpperTheory.Top.shape_closed_link_n_of_green", "shape_closed_link_n_of_green"),
         ("UpperTheory.Top.zeroFreeAll_of_topG", "zeroFreeAll_of_topG"),
         ("zeroFreeOn_of_tiedWin_cyc", "zeroFreeOn_of_tiedWin_cyc"),
         ("closed_linkDIVt_of_closed_bridge_kernel", "closed_linkDIVt_of_closed_bridge_kernel"),
         ("wordFacts_of", "wordFacts_of"), ("Formalism.L2.DIV.divClausesR_of", "divClausesR_of"),
         ("exists_divT", "exists_divT"), ("exists_pre2_of_fine_of_resChar_mem", "exists_pre2_of_fine_of_resChar_mem")]
with open(os.path.join(pdir, "tables", "route.tex"), "w", encoding="utf-8") as f:
    for key, short in ROUTE:
        t = T[key]
        if not t.get("present"): continue
        fl = [k for k in FLAG if t["cone_contains"].get(k)]
        f.write("\\path{%s} & %s & %s & %s & %s \\\\\n" % (short, c(t["cone"]["all"]), c(t["cone"]["project"]), c(t["cone"]["project_theorems"]), "yes" if fl else "\\textbf{no}"))
with open(os.path.join(pdir, "tables", "dependents.tex"), "w", encoding="utf-8") as f:
    for s, d in R["dependents"].items():
        f.write("\\path{%s} & %s & %s \\\\\n" % (s, c(d["count"]), "yes" if d["main_depends"] else "no"))
with open(os.path.join(pdir, "tables", "absent.tex"), "w", encoding="utf-8") as f:
    want = ["plugAll", "shapeWin", "everyE₂", "geoOf", "linkDIVt_closedK", "SlopeBoundFamilyStatement", "degree_value_of_determinant", "FrobeniusOrbitPlaceCount"]
    names = [k for k in want if not T[k].get("present") and "0 candidates" in T[k].get("note", "")]
    assert names == want, names
    f.write(", ".join("\\path{%s}" % n if n.isascii() else "\\leanu{%s}" % n for n in names))
rows = [l.rstrip("\n").split("\t") for l in open(os.path.join(qdir, "dependents_of_anyGeometry.tsv"), encoding="utf-8")][1:]
with open(os.path.join(pdir, "tables", "anygeo.tex"), "w", encoding="utf-8") as f:
    for i, (k, n) in enumerate(rows, 1): f.write("%d & %s & \\path{%s} \\\\\n" % (i, k, n))
with open(os.path.join(pdir, "tables", "watch.tex"), "w", encoding="utf-8") as f:
    for w, d in R["watch"].items():
        short = w.replace("GlobalTheory.Mem.Top.Bl.", "").replace("Formalism.BasicNotions.", "").replace("Formalism.L2.Geo.", "")
        if not d["declared_in_export"]:
            f.write("\\path{%s} & not in the export & --- \\\\\n" % short); continue
        refs = sorted(set(r.rsplit(" [", 1)[0].split(".")[-1] for r in d["referrers"]))
        n = d["direct_referrers_outside_own_block"]
        f.write("\\path{%s} & %d & %s \\\\\n" % (short, n, ", ".join("\\path{%s}" % r for r in refs[:4]) + (" …" if len(refs) > 4 else "") if n else "none"))
print("macros:", len(M), "| anyGeometry dependents:", len(rows))
for k in ["Nflagged", "NfreeProj", "NifaceDeps", "NaccDirect", "NdivClausesThm", "NpackageThm", "NgreenThm", "NstmtMain", "NgeoTiedP", "NgeoOver"]: print(" ", k, M[k])
